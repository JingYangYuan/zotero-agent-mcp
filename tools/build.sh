#!/bin/bash
# Build zotero-agent-mcp.xpi
# - wraps bridge/zotero-agent-mcp.mjs into plugin/bridge-source.js (jar-safe embedding)
# - wraps plugin/skill/SKILL.md into plugin/skill-source.js (released to the data dir at startup)
# - wraps plugin/clients.json into plugin/clients-source.js (agent-client registry)
# - zips plugin/ into build/zotero-agent-mcp.xpi and prints context-size diagnostics
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
export ROOT

node - <<'EOF'
const fs = require('fs');
const path = require('path');
const root = process.env.ROOT;

function embed(srcPath, destPath, varName, comment) {
  const src = fs.readFileSync(srcPath, 'utf8');
  fs.writeFileSync(destPath,
    `// Auto-generated by tools/build.sh from ${comment} — do not edit.\n` +
    `var ${varName} = ${JSON.stringify(src)};\n`);
  return src;
}

const bridge = embed(`${root}/bridge/zotero-agent-mcp.mjs`, `${root}/plugin/bridge-source.js`, 'BRIDGE_SRC', 'bridge/zotero-agent-mcp.mjs');
const skill = embed(`${root}/plugin/skill/SKILL.md`, `${root}/plugin/skill-source.js`, 'SKILL_SRC', 'plugin/skill/SKILL.md');
const clientsRaw = fs.readFileSync(`${root}/plugin/clients.json`, 'utf8');
const clients = JSON.parse(clientsRaw); // fail the build on malformed registry
embed(`${root}/plugin/clients.json`, `${root}/plugin/clients-source.js`, 'CLIENTS_SRC', 'plugin/clients.json');

// Sanity checks that would otherwise only show up at runtime.
const toolsMatch = bridge.match(/const TOOLS_ALL = \[/);
if (!toolsMatch) throw new Error('bridge: TOOLS_ALL not found — bridge-source embedding looks wrong');
if (!clients.clients?.length) throw new Error('clients.json: no clients defined');
const ids = new Set();
for (const c of clients.clients) {
  if (ids.has(c.id)) throw new Error(`clients.json: duplicate id ${c.id}`);
  ids.add(c.id);
}

console.log(`bridge-source.js: ${Buffer.byteLength(bridge)} bytes`);
console.log(`skill-source.js:  ${Buffer.byteLength(skill)} bytes`);
console.log(`clients-source.js: ${Buffer.byteLength(clientsRaw)} bytes (${clients.clients.length} clients)`);
EOF

node - <<'EOF'
// Report the MCP context cost of tools/list (what every agent pays on connect).
const { spawn } = require('child_process');
const path = require('path');
const child = spawn(process.execPath, [path.join(process.env.ROOT, 'bridge/zotero-agent-mcp.mjs')], {
  stdio: ['pipe', 'pipe', 'ignore'],
});
const t0 = Date.now();
let buf = '';
child.stdout.on('data', (d) => {
  buf += d.toString('utf8');
  let i;
  while ((i = buf.indexOf('\n')) >= 0) {
    const line = buf.slice(0, i);
    buf = buf.slice(i + 1);
    if (!line.trim()) continue;
    let msg;
    try { msg = JSON.parse(line); } catch { continue; }
    if (msg.id === 2) {
      const bytes = Buffer.byteLength(JSON.stringify(msg.result));
      console.log(`tools/list: ${msg.result.tools.length} tools, ${bytes} bytes (~${Math.round(bytes / 4)} tokens), handshake ${Date.now() - t0}ms`);
      child.kill();
      process.exit(0);
    }
  }
});
child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'initialize', params: {} }) + '\n');
child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id: 2, method: 'tools/list', params: {} }) + '\n');
EOF

mkdir -p "$ROOT/build"
rm -f "$ROOT/build/zotero-agent-mcp.xpi"
cd "$ROOT/plugin"
zip -q -r -X "$ROOT/build/zotero-agent-mcp.xpi" . -x "*.DS_Store" -x "clients.json"
echo "Built: $ROOT/build/zotero-agent-mcp.xpi ($(wc -c < "$ROOT/build/zotero-agent-mcp.xpi" | tr -d ' ') bytes)"
